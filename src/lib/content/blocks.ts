export function textFromValue(value: ContentBlockValue | undefined, fallback: string): string {
  if (!value || typeof value !== "object") return fallback;
  if ("text" in value && typeof value.text === "string") return value.text;
  if ("label" in value && typeof value.label === "string") return value.label;
  return fallback;
}

export function isLinkButtonValue(
  value: ContentBlockValue | undefined,
): value is { label: string; href: string; enabled: boolean } {
  return (
    !!value &&
    typeof value === "object" &&
    "label" in value &&
    "href" in value &&
    "enabled" in value
  );
}
